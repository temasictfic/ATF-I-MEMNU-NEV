"""Build helpers used by scripts/build.ps1 and the release workflows.

    python scripts/release_tools.py version
    python scripts/release_tools.py version-info  OUT.txt
    python scripts/release_tools.py installer-include OUT.iss
    python scripts/release_tools.py checksums OUT FILE...
    python scripts/release_tools.py model-assets OUT_DIR   (download + verify model files for publishing)
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from atfi_app.model_manager import load_manifest, manifest_digest  # noqa: E402
from atfi_app.version import __version__  # noqa: E402


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def cmd_version() -> None:
    print(__version__)


def cmd_version_info(out: str) -> None:
    major, minor, patch = (list(map(int, __version__.split(".")[:3])) + [0, 0, 0])[:3]
    template = (ROOT / "packaging" / "version_info.template").read_text(encoding="utf-8")
    text = (
        template.replace("{major}", str(major))
        .replace("{minor}", str(minor))
        .replace("{patch}", str(patch))
        .replace("{version}", __version__)
    )
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(text, encoding="utf-8")


def cmd_installer_include(out: str) -> None:
    """Inno Setup include with the app version and the NER model manifest."""
    m = load_manifest()
    lines = [
        "; Generated by scripts/release_tools.py, do not edit.",
        f'#define AppVersion "{__version__}"',
        f'#define ModelName "{m["name"]}"',
        f'#define ModelVersion "{m["version"]}"',
        f'#define ModelDigest "{manifest_digest(m)}"',
        f"#define ModelFileCount {len(m['files'])}",
    ]
    for i, f in enumerate(m["files"]):
        lines += [
            f'#define ModelFile{i}Name "{f["name"]}"',
            f'#define ModelFile{i}Sha "{f["sha256"]}"',
            f'#define ModelFile{i}Url "{f["urls"][0]}"',
            f'#define ModelFile{i}Mirror "{f["urls"][-1]}"',
        ]
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")


def cmd_checksums(out: str, *files: str) -> None:
    lines = [f"{_sha256(Path(f))}  {Path(f).name}" for f in files]
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


def cmd_model_assets(out_dir: str) -> None:
    """Download and verify every model file (from its last mirror) for publishing."""
    from atfi_app import net

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    m = load_manifest()
    for f in m["files"]:
        dest = out / f["name"]
        if dest.exists() and _sha256(dest) == f["sha256"]:
            continue
        net.download_file(f["urls"][-1], dest, expected_sha256=f["sha256"], expected_size=f["size"])
        print(f"ok  {f['name']}")
    print(json.dumps({"tag": f"model-{m['name']}-{m['version']}", "dir": str(out)}))


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    cmd, *rest = argv
    {
        "version": cmd_version,
        "version-info": cmd_version_info,
        "installer-include": cmd_installer_include,
        "checksums": cmd_checksums,
        "model-assets": cmd_model_assets,
    }[cmd](*rest)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
